import fs from "node:fs/promises";
import path from "node:path";

import { isMainModule } from "../../harness/shared/is-main-module.mjs";
import {
  getSectionNotesPath,
  getSectionNotesRelativePath
} from "../../harness/shared/load-section-notes.mjs";
import { resolvePageKey } from "../../harness/shared/resolve-page-key.mjs";
import { resolveSourceManifestPath } from "../../harness/shared/resolve-source-manifest-path.mjs";

async function readJson(filePath) {
  return JSON.parse(await fs.readFile(filePath, "utf8"));
}

async function pathExists(filePath) {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

function getExampleNotesPath(rootDir, pageKey) {
  return path.join(rootDir, "harness", "notes", `${pageKey}.example.json`);
}

function getExampleNotesRelativePath(pageKey) {
  return `harness/notes/${pageKey}.example.json`;
}

function buildStubFromSourceManifest({ pageKey, sourceManifest, sourceManifestRelativePath, examplePath }) {
  const sections = (sourceManifest.sections ?? []).map((entry) => ({
    id: entry.id,
    humanNotes: [
      `Stub generated by init-section-notes from ${sourceManifestRelativePath}.`,
      `Add overrides by setting any of: implementationPolicy, skillRoutingOverride, agentPrompt. See ${examplePath} for shapes and harness/contracts/section-notes.schema.json for the full schema. Sections without overrides may be deleted from this array.`
    ]
  }));
  return {
    schemaVersion: "1.0.0",
    manifestType: "section-notes",
    pageKey,
    sourceManifestPath: sourceManifestRelativePath,
    sections
  };
}

function buildExampleFromSourceManifest({ pageKey, sourceManifest, sourceManifestRelativePath }) {
  const firstSection = (sourceManifest.sections ?? [])[0];
  const sampleSectionId = firstSection?.id ?? "section-01";
  return {
    schemaVersion: "1.0.0",
    manifestType: "section-notes",
    pageKey,
    sourceManifestPath: sourceManifestRelativePath,
    sections: [
      {
        id: sampleSectionId,
        implementationPolicy: {
          pattern: "carousel",
          defaultImplementation: "swiper",
          repeatedContentSource: "blocks",
          themeCodeReuse: "avoid"
        },
        skillRoutingOverride: {
          recommendedSkill: "skills/theme/implement-section-from-figma/SKILL.md",
          reason: "Force the static section skill even when the manifest classified this section differently."
        },
        agentPrompt:
          "Implement this section as a 3-slide Swiper carousel with arrows below the slide track. Use blocks for the slides; do not bake content into settings.",
        humanNotes: [
          "Example file showing every override field. Runtime ignores *.example.json — only <page-key>.json is loaded.",
          "Copy fields you actually want into harness/notes/<page-key>.json under the same section id.",
          "implementationPolicy.pattern is enforced by section-result-validation: a 'carousel' pattern requires the implementation to use Swiper / scroll-snap / custom code, not static markup."
        ]
      }
    ]
  };
}

export async function initSectionNotes({ rootDir, pageKey, force = false }) {
  if (!pageKey) {
    throw new Error("init-section-notes requires --page <page-key>.");
  }

  const targetPath = getSectionNotesPath(rootDir, pageKey);
  const targetRelative = getSectionNotesRelativePath(pageKey);
  const examplePath = getExampleNotesPath(rootDir, pageKey);
  const exampleRelative = getExampleNotesRelativePath(pageKey);

  const stubExisted = await pathExists(targetPath);
  const exampleExisted = await pathExists(examplePath);

  if (!force && stubExisted && exampleExisted) {
    return {
      pageKey,
      path: targetRelative,
      examplePath: exampleRelative,
      created: false,
      reason: "notes file and example already exist; pass --force to overwrite"
    };
  }

  const sourceManifestPath = resolveSourceManifestPath({ pageKey, rootDir });
  if (!(await pathExists(sourceManifestPath.absolute))) {
    throw new Error(
      `source-manifest not found at ${sourceManifestPath.relative}. ` +
        `Initialize the page with skills/theme/initialize-page-from-figma/SKILL.md ` +
        `(it writes ${sourceManifestPath.relative}) before running init-section-notes.`
    );
  }
  const sourceManifest = await readJson(sourceManifestPath.absolute);

  await fs.mkdir(path.dirname(targetPath), { recursive: true });

  let stubCreated = false;
  if (force || !stubExisted) {
    const stub = buildStubFromSourceManifest({
      pageKey,
      sourceManifest,
      sourceManifestRelativePath: sourceManifestPath.relative,
      examplePath: exampleRelative
    });
    await fs.writeFile(targetPath, `${JSON.stringify(stub, null, 2)}\n`, "utf8");
    stubCreated = true;
  }

  let exampleCreated = false;
  if (force || !exampleExisted) {
    const example = buildExampleFromSourceManifest({
      pageKey,
      sourceManifest,
      sourceManifestRelativePath: sourceManifestPath.relative
    });
    await fs.writeFile(examplePath, `${JSON.stringify(example, null, 2)}\n`, "utf8");
    exampleCreated = true;
  }

  return {
    pageKey,
    path: targetRelative,
    examplePath: exampleRelative,
    created: stubCreated || exampleCreated,
    stubCreated,
    exampleCreated,
    sectionCount: sourceManifest.sections?.length ?? 0
  };
}

if (isMainModule(import.meta.url)) {
  const args = process.argv.slice(2);
  let rootDir = process.cwd();
  let pageKey = null;
  let force = false;
  for (let i = 0; i < args.length; i += 1) {
    const arg = args[i];
    if (arg === "--root") {
      rootDir = path.resolve(args[++i]);
    } else if (arg === "--page") {
      pageKey = args[++i];
    } else if (arg === "--force") {
      force = true;
    } else if (!arg.startsWith("--") && !pageKey) {
      pageKey = arg;
    }
  }
  if (!pageKey) {
    const resolved = resolvePageKey({ rootDir });
    pageKey = resolved.pageKey;
    process.stderr.write(
      `init-section-notes: resolved page-key "${pageKey}" from ${
        resolved.source === "branch" ? `git branch ${resolved.branch}` : "override"
      }\n`
    );
  }
  const summary = await initSectionNotes({ rootDir, pageKey, force });
  process.stdout.write(`${JSON.stringify(summary, null, 2)}\n`);
}
